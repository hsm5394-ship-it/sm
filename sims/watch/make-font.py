"""Subsets Noto Sans KR to the Hangul this film shows and writes it into style.css as two embedded weights.

    python3 -I make-font.py <folder with noto-sans-kr-korean-{500,800}-normal.woff2>

Run again after changing any Korean text. Needs fonttools and brotli.
"""
import base64, io, os, sys
from fontTools import subset
from fontTools.ttLib import TTFont

here = os.path.dirname(os.path.abspath(__file__))
chars = set()
for name in ("console.js", "film.js"):
    with open(os.path.join(here, name), encoding="utf8") as f:
        chars |= {c for c in f.read() if "가" <= c <= "힣"}
css = []
for weight, rng in ((500, "100 600"), (800, "601 900")):
    font = TTFont(os.path.join(sys.argv[1], f"noto-sans-kr-korean-{weight}-normal.woff2"))
    opt = subset.Options()
    opt.flavor = "woff2"
    opt.layout_features = []
    sub = subset.Subsetter(opt)
    sub.populate(unicodes=[ord(c) for c in chars])
    sub.subset(font)
    buf = io.BytesIO()
    font.flavor = "woff2"
    font.save(buf)
    b64 = base64.b64encode(buf.getvalue()).decode()
    css.append(f"@font-face{{font-family:'Watch KR';font-weight:{rng};font-style:normal;font-display:block;src:url(data:font/woff2;base64,{b64}) format('woff2');}}")
with open(os.path.join(here, "style.css"), "w") as f:
    f.write("/* generated by make-font.py: Noto Sans KR (OFL), only the glyphs the film uses */\n" + "\n".join(css) + "\n")
print(len(chars), "glyphs,", sum(len(c) for c in css) // 1024, "KB")
