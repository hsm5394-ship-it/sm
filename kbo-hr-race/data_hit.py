def dist(years, total, w=None):
    """연도 목록에 통산 합계를 경력 곡선 모양으로 나눈다."""
    n = len(years)
    if w is None:
        w = [1.0] * n
        if n > 2: w[0], w[1] = 0.45, 0.8
        if n > 5: w[-1], w[-2], w[-3] = 0.3, 0.6, 0.85
    s = sum(w); raw = [total * x / s for x in w]
    out = [int(r) for r in raw]
    for i in sorted(range(n), key=lambda i: raw[i] - out[i], reverse=True)[: total - sum(out)]:
        out[i] += 1
    return dict(zip(years, out))
